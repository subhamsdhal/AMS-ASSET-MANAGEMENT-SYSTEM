package com.mycompany.asset_management_system_ams;

import jakarta.servlet.ServletContext;

public class AdminSecurityAlertHelper {

    public static void sendAdminActionAlert(
            ServletContext context,
            Integer referenceId,
            String actionTitle,
            String moduleName,
            String actionPerformedBy,
            String senderRole,
            String senderEmail,
            String details
    ) {
        try {
            String cleanActionTitle = safe(actionTitle, "Administrative Action");
            String cleanModuleName = safe(moduleName, "System Administration");
            String cleanActionPerformedBy = safe(actionPerformedBy, "System User");
            String cleanSenderRole = formatRole(senderRole);
            String cleanSenderEmail = safe(senderEmail, "System Login Account");
            String cleanDetails = safe(details, "No additional details provided.");

            String subject = "IR-AMS Admin Alert - " + cleanActionTitle;

            // Fault (Medium, fixed): moduleName/details/actionPerformedBy/senderEmail are
            // free text embedded unescaped in this admin security alert email - same
            // recurring class as audit/10-maintenance.md Finding 1. Escape happens BEFORE
            // the newline->"<br>" substitution so the deliberate <br> tags aren't
            // themselves escaped away.
            String detailsTable = "<tr><th>Module:</th><td>" + HtmlEscapeUtil.escape(cleanModuleName) + "</td></tr>"
                    + "<tr><th>Reference ID:</th><td>" + safeReference(referenceId) + "</td></tr>"
                    + "<tr><th>Details:</th><td>" + HtmlEscapeUtil.escape(cleanDetails).replace("\n", "<br>") + "</td></tr>"
                    + "<tr><th>Action Performed By:</th><td>" + HtmlEscapeUtil.escape(cleanActionPerformedBy) + "</td></tr>"
                    + "<tr><th>Sender Role:</th><td>" + cleanSenderRole + "</td></tr>"
                    + "<tr><th>Sender Account:</th><td>" + HtmlEscapeUtil.escape(cleanSenderEmail) + "</td></tr>";

            String body = NotificationHelper.buildHtmlEmail(
                    "Super Admin",
                    cleanActionTitle,
                    detailsTable,
                    "This is an automated administrative alert generated by IR-AMS for monitoring and audit purposes."
            );

            NotificationHelper.sendAdminSecurityAlert(
                    context,
                    referenceId,
                    subject,
                    body
            );

        } catch (Exception e) {
            e.printStackTrace();
        }
    }

    public static void sendUserManagementAlert(
            ServletContext context,
            Integer referenceId,
            String actionPerformedBy,
            String senderRole,
            String senderEmail,
            String targetUsername,
            String targetRole,
            String actionType
    ) {
        String details = "Target Username: " + safe(targetUsername, "N/A") + "\n"
                + "Target Role: " + formatRole(targetRole) + "\n"
                + "Action Type: " + safe(actionType, "N/A");

        sendAdminActionAlert(
                context,
                referenceId,
                "User Management - " + safe(actionType, "Updated"),
                "User Management",
                actionPerformedBy,
                senderRole,
                senderEmail,
                details
        );
    }

    public static void sendSettingsChangedAlert(
            ServletContext context,
            Integer referenceId,
            String actionPerformedBy,
            String senderRole,
            String senderEmail,
            String settingName,
            String oldValue,
            String newValue
    ) {
        String details = "Setting Name: " + safe(settingName, "N/A") + "\n"
                + "Old Value: " + safe(oldValue, "N/A") + "\n"
                + "New Value: " + safe(newValue, "N/A");

        sendAdminActionAlert(
                context,
                referenceId,
                "System Setting Changed",
                "System Settings",
                actionPerformedBy,
                senderRole,
                senderEmail,
                details
        );
    }

    public static void sendBackupRestoreAlert(
            ServletContext context,
            Integer referenceId,
            String actionPerformedBy,
            String senderRole,
            String senderEmail,
            String operationType,
            String fileName,
            String status
    ) {
        String details = "Operation Type: " + safe(operationType, "N/A") + "\n"
                + "File Name: " + safe(fileName, "N/A") + "\n"
                + "Status: " + safe(status, "N/A");

        sendAdminActionAlert(
                context,
                referenceId,
                "Database " + safe(operationType, "Backup/Restore"),
                "Backup and Restore",
                actionPerformedBy,
                senderRole,
                senderEmail,
                details
        );
    }

    public static void sendSecurityWarningAlert(
            ServletContext context,
            Integer referenceId,
            String actionPerformedBy,
            String senderRole,
            String senderEmail,
            String warningTitle,
            String warningDetails
    ) {
        sendAdminActionAlert(
                context,
                referenceId,
                "Security Warning - " + safe(warningTitle, "Important"),
                "Security Monitoring",
                actionPerformedBy,
                senderRole,
                senderEmail,
                warningDetails
        );
    }

    private static String safeReference(Integer referenceId) {
        if (referenceId == null || referenceId <= 0) {
            return "N/A";
        }

        return String.valueOf(referenceId);
    }

    private static String formatRole(String role) {
        if (role == null || role.trim().isEmpty()) {
            return "System User";
        }

        return role.trim().replace("_", " ");
    }

    private static String safe(String value, String fallback) {
        if (value == null || value.trim().isEmpty()) {
            return fallback;
        }

        return value.trim();
    }
}